  private DtcDescriptions() {}
  public static String describe(String code) {
    if (code == null) return "کد نامشخص";
    String key = code.toUpperCase(Locale.US).trim();
    String known = CODES.get(key);
    if (known != null) return known;
    if (!key.matches("[PCBU][0-3][0-9A-F]{3}")) return "قالب کد ناشناخته؛ بررسی داده خام ECU لازم است";
    String area;
    switch (key.charAt(0)) {
      case 'P': area = "قوای محرکه و موتور"; break;
      case 'C': area = "شاسی"; break;
      case 'B': area = "بدنه"; break;
      default: area = "شبکه ارتباطی";
    }
    if (key.charAt(1) == '1' || key.charAt(1) == '3')
      return "کد اختصاصی سازنده در بخش " + area + "؛ شرح معتبر برای این ECU موجود نیست";
    return "کد بخش " + area + "؛ شرح دقیق هنوز در بانک فارسی ثبت نشده است";
  }
