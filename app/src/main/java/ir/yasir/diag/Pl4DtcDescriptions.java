  private Pl4DtcDescriptions() {}

  public static String obdCode(String raw) {
    if (raw == null) return "RAW ?";
    String h = raw.toUpperCase(Locale.US).replaceAll("[^0-9A-F]", "");
    if (h.length() != 4) return "RAW " + raw;
    try {
      int value = Integer.parseInt(h, 16);
      char system = "PCBU".charAt((value >>> 14) & 3);
      return "" + system + ((value >>> 12) & 3) +
          String.format(Locale.US, "%03X", value & 0x0FFF);
    } catch (Exception ignored) {
      return "RAW " + raw;
    }
  }

  public static String describe(String raw) {
    if (raw == null) return "شرح تأییدشده‌ای برای این کد وجود ندارد";
    String h = raw.toUpperCase(Locale.US).replaceAll("[^0-9A-F]", "");
    String special = RAW.get(h);
    if (special != null) return special + " (مرجع PL4 / نیازمند تطبیق با ECU)";
    return "شرح اختصاصی تأیید نشده؛ کد خام را نگه دارید. " +
        DtcDescriptions.describe(obdCode(raw));
  }
